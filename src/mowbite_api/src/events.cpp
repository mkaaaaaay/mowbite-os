Field Object(std::string name, std::string text, std::vector<Field> fields, bool required = false) {
  return {std::move(name), Type::kObject, "", required, std::move(text), {}, false, std::move(fields), ""};
}

Field Nullable(Field field) {
  field.nullable = true;
  return field;
}

